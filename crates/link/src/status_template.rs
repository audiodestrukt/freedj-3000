//! playing a rekordbox-analysed track from USB at 126 BPM, tempo master) on
//! 2026-08-26, with the device name (0x0b..=0x1e, 20 bytes) blanked.
//! `ProDjLink::build_status` copies this and overwrites the documented dynamic
//! fields; every byte we do not understand is therefore exactly what Pioneer
//! firmware sends, which is the safest thing to put on the wire.
//!
//! Byte 0x1f is 0x01 on a real device.  It sits one byte past the name, and the
//! original redaction of this capture zeroed 0x0b..=0x1f (21 bytes) instead of
//! 0x0b..=0x1e (20) — an off-by-one that left 0x1f = 0x00.  The XDJ tolerated it
//! for ordinary status but ABORTED every tempo-master handoff to us over it (it
//! set Mh=us, saw our malformed status, reverted Mh and kept MASTER).  Restored
